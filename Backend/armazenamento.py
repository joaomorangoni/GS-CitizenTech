"""Persistência PostgreSQL com conexão por operação."""

from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row

from .config import RISCOS


def conectar(url):
    return psycopg.connect(url, row_factory=dict_row, connect_timeout=5)


def inicializar(url):
    with conectar(url) as conexao:
        conexao.execute("""CREATE TABLE IF NOT EXISTS leituras (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            distancia_cm DOUBLE PRECISION, temperatura_c DOUBLE PRECISION,
            umidade_relativa DOUBLE PRECISION, risco_esp32 TEXT NOT NULL,
            risco_python TEXT NOT NULL, tempo_ms BIGINT NOT NULL,
            recebido_em TIMESTAMPTZ NOT NULL
        )""")


def normalizar(registro):
    registro = dict(registro)
    registro["recebido_em"] = registro["recebido_em"].astimezone(timezone.utc).isoformat()
    return registro


def salvar(url, leitura):
    registro = dict(leitura, recebido_em=datetime.now(timezone.utc))
    with conectar(url) as conexao:
        linha = conexao.execute("""INSERT INTO leituras
            (distancia_cm, temperatura_c, umidade_relativa, risco_esp32,
             risco_python, tempo_ms, recebido_em)
            VALUES (%(distancia_cm)s, %(temperatura_c)s, %(umidade_relativa)s,
                    %(risco_esp32)s, %(risco_python)s, %(tempo_ms)s, %(recebido_em)s)
            RETURNING *""", registro).fetchone()
    return normalizar(linha)


def consultar(url, limite=100, offset=0):
    with conectar(url) as conexao:
        linhas = conexao.execute(
            "SELECT * FROM leituras ORDER BY id DESC LIMIT %s OFFSET %s", (limite, offset)).fetchall()
    return [normalizar(linha) for linha in linhas]


def resumir(url):
    contagens = dict.fromkeys(RISCOS, 0)
    with conectar(url) as conexao:
        for linha in conexao.execute("SELECT risco_python, COUNT(*) AS total FROM leituras GROUP BY risco_python"):
            contagens[linha["risco_python"]] = linha["total"]
        medias = conexao.execute("""SELECT AVG(distancia_cm) AS distancia_cm,
            AVG(temperatura_c) AS temperatura_c, AVG(umidade_relativa) AS umidade_relativa
            FROM leituras""").fetchone()
        divergencias = conexao.execute(
            "SELECT COUNT(*) AS total FROM leituras WHERE risco_esp32 != risco_python").fetchone()["total"]
    return {"total_leituras": sum(contagens.values()), "por_risco": contagens,
            "medias": medias, "riscos_divergentes": divergencias}
